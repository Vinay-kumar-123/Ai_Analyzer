"use client";

import { FiCopy, FiDownload, FiCheck } from "react-icons/fi";

/**
 * ============================================================================
 * AI Learning OS
 * Summary Tab
 * ----------------------------------------------------------------------------
 * Responsibilities
 *
 * • Display AI summary
 * • Display learning outcome
 * • Copy summary
 * • Export PDF
 *
 * NEVER
 * - API Calls
 * - Polling
 * - Lazy Generation
 * - Business Logic
 * ============================================================================
 */

import { Copy, Download, Check, Sparkles, Award, Tag } from "lucide-react";

export default function SummaryTab({
  analysis,
  copy,
  copied,
  buildPDF,
}) {
  if (!analysis) return null;

  const {
    summary = "",
    outcome = "",
    contentType = "General",
  } = analysis;

  return (
    <section className="space-y-6 text-left">

      {/* Header */}
      <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h2 className="text-xl font-black text-white tracking-tight flex items-center gap-2">
            <Sparkles size={18} className="text-yellow-400" />
            <span>AI Executive Summary</span>
          </h2>
          <p className="mt-1 text-xs text-slate-400">
            Synthesized overview and critical targets from video transcripts.
          </p>
        </div>

        <div className="flex gap-2">
          <button
            type="button"
            onClick={() => copy(summary, "summary")}
            className="flex items-center gap-2 rounded-xl border border-white/10 bg-[#0b0f19]/35 px-4.5 py-2.5 text-xs font-bold text-slate-200 transition-all hover:bg-white/5 hover:border-white/20 active:scale-98"
          >
            {copied === "summary" ? <Check size={14} className="text-emerald-400" /> : <Copy size={14} />}
            <span>{copied === "summary" ? "Copied" : "Copy Notes"}</span>
          </button>

          <button
            type="button"
            onClick={() =>
              buildPDF({
                type: "summary",
                data: analysis,
              })
            }
            className="flex items-center gap-2 rounded-xl bg-blue-600 hover:bg-blue-500 px-4.5 py-2.5 text-xs font-bold text-white transition-all active:scale-98 shadow-md shadow-blue-500/10"
          >
            <Download size={14} />
            <span>Export PDF</span>
          </button>
        </div>
      </div>

      {/* Grid of details */}
      <div className="grid gap-6 md:grid-cols-2">
        {/* Summary Card */}
        <div className="rounded-3xl border border-white/5 bg-[#0b0f19]/30 p-6 md:p-8 space-y-4">
          <h3 className="text-sm font-black uppercase tracking-wider text-blue-400 flex items-center gap-2">
            <Sparkles size={14} />
            <span>Summary Overview</span>
          </h3>
          <p className="leading-relaxed text-sm text-slate-300 whitespace-pre-wrap font-medium">
            {summary || "Summary details are being generated by the workspace models."}
          </p>
        </div>

        {/* Learning Outcome Card */}
        <div className="rounded-3xl border border-white/5 bg-[#0b0f19]/30 p-6 md:p-8 space-y-4">
          <h3 className="text-sm font-black uppercase tracking-wider text-emerald-400 flex items-center gap-2">
            <Award size={14} />
            <span>Target Learning Outcome</span>
          </h3>
          <p className="leading-relaxed text-sm text-slate-300 whitespace-pre-wrap font-medium">
            {outcome || "Learning outcomes are being synthesized by the workspace models."}
          </p>
        </div>
      </div>

      {/* Content Type tag container */}
      <div className="rounded-3xl border border-white/5 bg-[#0b0f19]/20 p-6 flex items-center justify-between">
        <div className="flex items-center gap-3">
          <div className="w-9 h-9 rounded-xl bg-white/5 flex items-center justify-center text-slate-400">
            <Tag size={16} />
          </div>
          <div>
            <h4 className="text-xs font-bold text-white leading-none">Content Classification</h4>
            <p className="text-[10px] text-slate-500 font-bold mt-1">AI determined categorization</p>
          </div>
        </div>
        <span className="bg-indigo-500/10 border border-indigo-500/20 text-indigo-400 text-xs font-bold uppercase tracking-wider px-3.5 py-1.5 rounded-xl">
          {contentType}
        </span>
      </div>

    </section>
  );
}